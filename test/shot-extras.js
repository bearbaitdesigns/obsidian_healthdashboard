const path = require('path'); const fs = require('fs');
const { registry, makeApp } = require('./mock'); const { seed } = require('./run-seed'); const { seedNew, daysAgo } = require('./seed-new');
const PluginClass = require(path.resolve('dist/main.js'));
const src = fs.readFileSync('test/shot.js', 'utf8');
eval(src.slice(src.indexOf('const esc'), src.indexOf('(async')));
(async () => {
  const app = makeApp(); await seed(app); await seedNew(app);
  const add = (p, fm) => app.vault.create(p, '---\n' + Object.entries(fm).map(([k, v]) => k + ': ' + JSON.stringify(v)).join('\n') + '\n---\n');
  await add('Health Notes/Missed records/a.md', { entry: 'missed-event', tracker: 'migraine', month: daysAgo(60).slice(0, 7), roughly: 'both at the start of the month', count: 2, severity: 'Severe', notes: 'Was travelling, forgot to log.' });
  await add('Health Notes/Missed records/b.md', { entry: 'missed-event', tracker: 'migraine', roughly: 'sometime last winter', count: 1 });
  await add('Health Notes/Notes/Migraine/n.md', { entry: 'health-note', tracker: 'migraine', date: daysAgo(3), title: 'New job', note: 'Started a new job with screen work all day. Migraines seem worse in the afternoon.' });
  await add('Health Notes/Notes/Migraine/m.md', { entry: 'health-note', tracker: 'migraine', date: daysAgo(30), note: 'Doctor suggested magnesium; started 400 mg at bedtime.' });
  const host = new PluginClass(app, { id: 'health-dashboard', name: 'Health Dashboard' }); host._loaded = true; await host.onload();
  await new Promise(r => setTimeout(r, 400));
  await registry.commands['health-dashboard:open-dashboard'].callback();
  const v = app.workspace.getLeavesOfType('health-dashboard')[0].view;
  v.contentEl.querySelectorAll('.hd-tab').find((b) => b.textContent === 'Migraine').click();
  const ex = v.contentEl.querySelector('.hd-extras');
  const css = fs.readFileSync('dist/styles.css', 'utf8');
  const vars = fs.readFileSync('test/out-overview-light.html', 'utf8').match(/<style>([\s\S]*?)\/\* Period Tracker/)[1];
  const extra = '.clickable-icon{background:transparent;box-shadow:none;padding:4px} body{padding:20px;max-width:1000px}';
  fs.writeFileSync('test/out-extras-light.html', `<!doctype html><meta charset=utf-8><style>${vars}${css}${extra}</style><body class="theme-light"><div class="hd-root">${html(ex)}</div></body>`);
  process.exit(0);
})();
