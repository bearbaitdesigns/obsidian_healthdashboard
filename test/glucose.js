require('./clock');
const assert = require('assert'); const path = require('path'); const fs = require('fs');
const { registry, makeApp, Modal } = require('./mock');
const PluginClass = require(path.resolve(process.argv[2]));
const flush = () => new Promise((r) => setTimeout(r, 350));
const G = PluginClass._glucose;
(async () => {
  // --- CSV parsing: Dexcom (mg/dL, ISO dates, Low/High, non-EGV rows skipped)
  const dex = ['Index,Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Event Subtype,Patient Info,Device Info,Source Device ID,Glucose Value (mg/dL),Insulin Value (u),Carb Value (grams)',
    '1,,FirstName,,Alex,,,,,', '2,2026-11-01T00:03:12,EGV,,,,iPhone,112,,', '3,2026-11-01T00:08:12,EGV,,,,iPhone,Low,,', '4,2026-11-01T00:13:12,Calibration,,,,iPhone,130,,', '5,2026-11-02T07:00:00,EGV,,,,iPhone,High,,'].join('\n');
  let r = G.parseCgmCsv(dex);
  assert.strictEqual(r.format, 'Dexcom'); assert.strictEqual(r.count, 3); assert.strictEqual(r.days.length, 2);
  assert.deepStrictEqual(r.days[0].points, [{ min: 3, mg: 112 }, { min: 8, mg: 39 }]);
  assert.strictEqual(r.days[1].points[0].mg, 401);
  // --- LibreView (mmol/L, metadata line first, day-first dates, record types 0/1 kept, 6 skipped)
  const libre = ['Glucose Data,Generated on,13-11-2026 10:00 UTC,Generated by,Alex', 'Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L,Non-numeric Rapid-Acting Insulin',
    'FreeStyle LibreLink,abc,13-11-2026 08:15,0,5.6,,', 'FreeStyle LibreLink,abc,13-11-2026 08:30,1,,6.1,', 'FreeStyle LibreLink,abc,13-11-2026 08:31,6,,,note'].join('\n');
  r = G.parseCgmCsv(libre);
  assert.strictEqual(r.format, 'FreeStyle Libre'); assert.strictEqual(r.unit, 'mmol'); assert.strictEqual(r.order, 'dmy');
  assert.deepStrictEqual(r.days.map((d) => d.date), ['2026-11-13']);
  assert.deepStrictEqual(r.days[0].points, [{ min: 495, mg: 101 }, { min: 510, mg: 110 }]);
  // ambiguous month/day -> flagged; explicit order respected
  const amb = 'Device Timestamp,Historic Glucose mg/dL\n03-11-2026 08:00,120\n04-11-2026 08:00,130';
  assert.strictEqual(G.parseCgmCsv(amb).ambiguous, true);
  assert.strictEqual(G.parseCgmCsv(amb, 'dmy').days[0].date, '2026-11-03');
  assert.strictEqual(G.parseCgmCsv(amb, 'mdy').days[0].date, '2026-03-11');
  assert(G.parseCgmCsv('a,b\n1,2').error, 'no glucose column');

  // --- Stats on a synthetic day: 288 readings, 20% low (incl. one 30-min low run), 60% in range, 20% high
  const s = Object.assign({}, G.DEFAULT_SETTINGS);
  const pts = [];
  for (let i = 0; i < 288; i++) pts.push({ min: i * 5, mg: i < 6 ? 50 : i < 58 ? 65 : i < 230 ? 120 : 200 });
  const day = { kind: 'cgm', date: '2026-11-08', points: pts };
  const st = G.computeStats([day], s, '2026-11-08', '2026-11-08');
  assert.strictEqual(st.src, 'cgm'); assert.strictEqual(st.n, 288);
  assert.strictEqual(Math.round(st.share.vlow * 10) / 10, 2.1); assert.strictEqual(Math.round(st.share.in), 60);
  assert.strictEqual(st.lows.length, 1, 'one continuous low'); assert.strictEqual(st.lows[0].nadir, 50);
  assert.strictEqual(st.gmi, G.gmiOf(st.mean)); assert(Math.abs(G.gmiOf(154) - 7.0) < 0.05, 'GMI 154 mg/dL ~ 7.0%');
  assert(st.cv > 0 && Math.round(st.active) === 100);
  assert.strictEqual(st.agpHours, 24);
  // meter-only: shares of readings; short CGM lows (<15 min) don't count
  const meter = [{ kind: 'meter', date: '2026-11-08', time: '07:00', mg: 60, context: 'Fasting', medications: [] }, { kind: 'meter', date: '2026-11-08', time: '12:00', mg: 140, context: 'After meal', medications: [] }];
  const ms = G.computeStats(meter, s, '2026-11-08', '2026-11-08');
  assert.strictEqual(ms.src, 'meter'); assert.strictEqual(ms.share.low, 50); assert.strictEqual(ms.lows.length, 1); assert.strictEqual(ms.gmi, null);
  const short = G.computeStats([{ kind: 'cgm', date: '2026-11-08', points: [{ min: 0, mg: 120 }, { min: 5, mg: 60 }, { min: 10, mg: 120 }] }], s, '2026-11-08', '2026-11-08');
  assert.strictEqual(short.lows.length, 0, '5-minute dip is not a low');
  // target presets
  assert.deepStrictEqual([G.targetOf({ rangePreset: 'pregnancy' }).low, G.targetOf({ rangePreset: 'pregnancy' }).high], [63, 140]);
  assert.strictEqual(G.fmtG({ unit: 'mmol/L' }, 180), '10.0 mmol/L'); assert.strictEqual(G.fmtG({ unit: 'mg/dL' }, 180), '180 mg/dL');

  // --- In the plugin: log a meter reading, import CGM data, dashboard, overview, report
  const app = makeApp();
  const host = new PluginClass(app, { id: 'health-dashboard', name: 'Health Dashboard' }); host._loaded = true; await host.onload(); await flush();
  assert(host.glucose, 'glucose tracker on by default');
  registry.commands['glucose-tracker:log-reading'].callback();
  const m = Modal.opened[Modal.opened.length - 1];
  m.valIn.value = '3.2'; m.dateIn.value = '2026-11-09'; m.timeIn.value = '07:10'; m.ctxC.set && m.ctxC.set(['Fasting']);
  await m.save(); await flush();
  const f = [...app.__files.keys()].find((k) => k.startsWith('Glucose/Readings/'));
  assert(f, 'reading note created'); const fm = app.__files.get(f).fm;
  assert.strictEqual(fm.entry, 'glucose-reading'); assert.strictEqual(fm.glucose_mg_dl, 58); assert.strictEqual(fm.glucose_mmol_l, 3.2);
  // import 14 days of CGM
  const lines = ['Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Glucose Value (mg/dL)'];
  for (let d = 0; d < 14; d++) for (let i = 0; i < 288; i++) {
    const day = new Date(2026, 9, 27 + d), mins = i * 5;
    const v = Math.round(130 + 50 * Math.sin((mins / 1440) * 2 * Math.PI - 1) + (i % 7) * 3 - (d === 3 && i > 30 && i < 40 ? 80 : 0));
    lines.push(day.getFullYear() + '-' + String(day.getMonth() + 1).padStart(2, '0') + '-' + String(day.getDate()).padStart(2, '0') + 'T' + String(Math.floor(mins / 60)).padStart(2, '0') + ':' + String(mins % 60).padStart(2, '0') + ':00,EGV,' + v);
  }
  const parsed = G.parseCgmCsv(lines.join('\n'));
  let res = await host.glucose.importDays(parsed.days, 'Dexcom', 'clarity.csv');
  assert.strictEqual(res.days, 14); assert.strictEqual(res.added, 14 * 288);
  res = await host.glucose.importDays(parsed.days, 'Dexcom', 'clarity.csv');
  assert.strictEqual(res.added, 0, 'second import adds nothing');
  await flush();
  const dayNotes = [...app.__files.keys()].filter((k) => k.startsWith('Glucose/CGM/'));
  assert.strictEqual(dayNotes.length, 14, 'one note per day');
  const all = host.glucose.getRecords();
  assert.strictEqual(all.filter((x) => x.kind === 'cgm').length, 14);
  const st14 = host.glucose.stats('14');
  console.log('14 days:', 'TIR', G.fixed(st14.share.in), 'avg', host.glucose.fmt(st14.mean), 'GMI', st14.gmi, 'CV', st14.cv.toFixed(0) + '%', 'lows', st14.lows.length, 'active', G.fixed(st14.active));
  assert.strictEqual(st14.src, 'cgm'); assert(st14.lows.length >= 1);

  await registry.commands['health-dashboard:open-dashboard'].callback();
  const root = app.workspace.getLeavesOfType('health-dashboard')[0].view.contentEl;
  const tabBtn = root.querySelectorAll('.hd-tab').find((b) => b.textContent === 'Glucose');
  assert(tabBtn, 'Glucose tab'); tabBtn.click(); await flush();
  const t = root.textContent;
  for (const w of ['Time in range', 'Average glucose', 'Time below range', 'Variability (CV)', 'Time in ranges', 'Daily pattern', 'Daily average', 'CGM days in this period', 'Meter readings in this period'])
    assert(t.includes(w), 'dashboard shows ' + w);
  const grid = root.querySelector('.gl-grid');
  assert(grid.children[0].cls.has('hk-calendar'), 'calendar first (left)');
  assert(root.querySelectorAll('svg').some((x) => /gl-agp/.test((x.attrs && x.attrs.class) || '')), 'daily pattern chart');
  root.querySelectorAll('.hd-tab')[0].click(); await flush();
  assert(root.querySelectorAll('.hd-sum').some((c) => c.cls.has('is-glucose')), 'overview card');
  assert(root.querySelector('.hd-actions').children.some((b) => b.textContent === 'Log glucose'), 'quick log button');
  // help + report
  const h = PluginClass._help ? PluginClass._help : null;
  const bytes = G.buildReport(host.glucose, { from: '2026-10-27', to: '2026-11-09', name: 'Alex Example', includeMeds: true, includeReadings: true });
  const pdf = Buffer.from(bytes).toString('latin1');
  assert(pdf.startsWith('%PDF') && pdf.includes('Glucose report'), 'valid PDF');
  for (const w of ['Time in ranges', 'Daily pattern', 'Day by day', 'Meter readings']) assert(pdf.includes(w), 'report has ' + w);
  if (process.argv[3]) fs.writeFileSync(process.argv[3], Buffer.from(bytes));
  // since last visit summary
  const groups = host.sinceGroups('2026-10-20', '2026-11-09');
  const gg = groups.find((g) => g.key === 'glucose');
  assert(gg && gg.lines[0].startsWith('Time in range'), 'since-last-visit glucose');
  console.log('GLUCOSE OK'); process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
